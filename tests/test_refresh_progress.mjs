import assert from 'node:assert/strict';
import {progressState,activeRun,createCloudClient} from '../static/refresh-progress.js';
assert.equal(activeRun({status:'queued'}),true);
assert.equal(activeRun({status:'completed'}),false);
assert.equal(progressState({status:'queued'}).value,null);
assert.equal(progressState({status:'completed',conclusion:'failure'}).failed,true);
assert.equal(progressState({status:'completed',conclusion:'success'}).published,true);
const stage=progressState({status:'in_progress'},[{name:'build',status:'in_progress',steps:[{status:'completed'},{status:'in_progress',name:'Refresh ETF price histories'}]}]);
assert.equal(stage.value,.5);assert.match(stage.label,/Refresh ETF/);
assert.match(progressState({status:'in_progress'},[{name:'deploy',status:'in_progress',steps:[]}]).label,/Publishing/);
assert.equal(progressState({status:'in_progress'},[{name:'build',status:'completed',conclusion:'failure'}]).failed,true);
let calls=[];
const client=createCloudClient({getToken:()=> 'test-only',fetcher:async(url,options)=>{calls.push({url,options});return {ok:true,status:204};}});
await client.dispatch();
assert.equal(calls[0].options.headers.Authorization,'Bearer test-only');
assert.deepEqual(JSON.parse(calls[0].options.body),{ref:'main',inputs:{intraday:true}});
assert.equal(calls[0].options.method,'POST');
const limited=createCloudClient({fetcher:async()=>({ok:false,status:429})});
await assert.rejects(limited.latest(),/request limit/);
const latest=createCloudClient({fetcher:async()=>({ok:true,status:200,json:async()=>({workflow_runs:[{id:2,status:'completed'},{id:1,status:'in_progress'}]})})});
assert.equal((await latest.latest()).id,1);
console.log('Cloud refresh queued, steps, publishing, failure, authentication, dispatch and rate-limit checks passed');
