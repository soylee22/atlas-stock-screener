import assert from 'node:assert/strict';
import {customSMA,smaSettings,usesCustomSMA} from '../static/sma-math.js';
import {rankedCSV} from '../static/ranked-export.js';
import {quadrantModel,orderPoints} from '../static/quadrant-math.js';
import {chartCoverage,selectSnapshot} from '../static/snapshot-engine.js';
const history={daily:{closes:[10,20,30,40],dates:['2026-01-01','2026-01-02','2026-01-05','2026-01-06']},weekly:{closes:[10,30],dates:['2025-12-26','2026-01-02']}};
let row=customSMA({symbol:'A'},history,'GBp',{GBP:{rate:1.25}},{interval:'daily',window:2});
assert.equal(row.sma_custom,35*.0125);assert.equal(row.sma_custom_distance,(40/35-1)*100);
row=customSMA({symbol:'A'},history,'USD',{USD:{rate:1}},{interval:'weekly',window:2});
assert.equal(row.sma_custom,20);assert.equal(row.sma_custom_distance,100);
assert.match(row.sma_custom_period,/reference 2026-01-06/);
assert.equal(customSMA({},history,'USD',{}, {interval:'daily',window:5}).sma_custom_distance,null);
assert.throws(()=>smaSettings(new URLSearchParams('sma_window=261&sma_interval=weekly')));
assert(usesCustomSMA(new URLSearchParams('filters=[{"field":"sma_custom_distance"}]')));
const schema={regions:{us:'US'},columns:[{key:'sma_custom_distance',kind:'percent'}]};
const selected=selectSnapshot([{...row,active:true,main_listing:true,instrument:'stock',region_code:'us'}],schema,new URLSearchParams('sort=sma_custom_distance&filters=[{"field":"sma_custom_distance","op":"gt","value":0}]'));
assert.equal(selected.length,1);
assert.deepEqual(chartCoverage([{sma_200w_distance:null,technical_version:0},{sma_200w_distance:null,technical_version:1}], 'sma_200w_distance','sma_200w_distance',{}),{awaiting:1,unavailable:1});
const fields={x:{kind:'number'},y:{kind:'number'}};
const options={x:'x',y:'y',xPrefer:'higher',yPrefer:'higher',xScale:'linear',yScale:'linear',split:'median',order:'balanced'};
const model=quadrantModel([{symbol:'LOW',name:'low',x:1,y:1},{symbol:'HIGH',name:'=bad,"company"',x:10,y:10},{symbol:'TRADE',x:20,y:2}],options,fields);
const ranked=orderPoints(model.points,options.order);
const csv=rankedCSV(ranked,options);const lines=csv.trim().split('\r\n');
assert.equal(lines.length,4);assert.equal(lines[1].split(',')[1],ranked[0].row.symbol);
assert.match(csv,/balanced_score/);assert.match(csv,/pareto_frontier/);assert.match(csv,/'=bad/);
const periodCSV=rankedCSV([{...ranked[0],row:{symbol:'PERIOD',income_period:'FY INCOME',cf_period:'TTM CASH',fcf_growth_period:'FY CASH GROWTH'}}],{...options,x:'fcf',y:'fcf_change'});
assert.match(periodCSV,/TTM CASH/);assert.match(periodCSV,/FY CASH GROWTH/);assert(!periodCSV.includes('FY INCOME'));
assert(!rankedCSV([{...ranked[0],row:{symbol:'UNKNOWN',income_period:'FY INCOME'}}],{...options,x:'div_yield',y:'pe'}).includes('FY INCOME'));
console.log('Custom SMA, coverage, filters and ranked export checks passed');
